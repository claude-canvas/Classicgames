// lay out text centred at the origin: polylines in sign units (glyph height 6, advance 5.6)
export function layout(text) {
  const out = [], adv = 5.6, w = text.length * adv - 1.6;
  [...text].forEach((ch, i) => { for (const line of GLYPHS[ch] || []) out.push(line.map(([x, y]) => [x + i * adv - w / 2, y - 3])); });
  return out;
}
